package lesson04;

import org.h2.jdbcx.JdbcDataSource;

import javax.sql.DataSource;
import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.SQLException;

public class Database {
    public static DataSource createDataSource(String name) {
        JdbcDataSource dataSource = new JdbcDataSource();
        dataSource.setURL("jdbc:h2:mem:" + name + ";DB_CLOSE_DELAY=-1");
        return dataSource;
    }

    public static void initialize(DataSource dataSource) throws SQLException {
        String[] queries = {
                """
                CREATE TABLE IF NOT EXISTS students (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    name VARCHAR(100) NOT NULL,
                    group_name VARCHAR(50) NOT NULL,
                    grade DOUBLE PRECISION NOT NULL CHECK (grade BETWEEN 0 AND 100)
                )
                """,
                """
                CREATE TABLE IF NOT EXISTS courses (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    name VARCHAR(100) NOT NULL,
                    free_seats INT NOT NULL CHECK (free_seats >= 0)
                )
                """,
                """
                CREATE TABLE IF NOT EXISTS enrollments (
                    student_id BIGINT NOT NULL REFERENCES students(id),
                    course_id BIGINT NOT NULL REFERENCES courses(id),
                    PRIMARY KEY (student_id, course_id)
                )
                """
        };

        try (Connection connection = dataSource.getConnection()) {
            for (String query : queries) {
                try (PreparedStatement statement = connection.prepareStatement(query)) {
                    statement.executeUpdate();
                }
            }
        }
    }
}
